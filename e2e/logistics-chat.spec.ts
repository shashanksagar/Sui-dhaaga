import { expect, test } from "@playwright/test";
import { act, approvePending, courier, createOrder, login, mutate, png, readOrder } from "./helpers";
import type { MessageDTO } from "../src/lib/contracts";
test("masked reviewed chat, 50/25/25, paid design and free fitting loops, approval and feedback", async ({ browser }) => {
  test.setTimeout(240000);
  const customer = await browser.newContext(), tailor = await browser.newContext(), admin = await browser.newContext(), outsider = await browser.newContext();
  try {
    await login(customer, "customer@sui.local"); await login(tailor, "tailor1@sui.local"); await login(admin, "admin@sui.local"); await login(outsider, "tailor2@sui.local");
    const id = await createOrder(customer), pending = await readOrder(customer, id), privateOrder = await readOrder(admin, id);
    expect(pending).not.toHaveProperty("tailorIdentity"); expect(pending).not.toHaveProperty("pickupAddress");
    expect(JSON.stringify(pending)).not.toContain(privateOrder.tailorIdentity!.email);
    expect((await readOrder(tailor, id)).designSpecifications).toBe("");
    const blocked = await mutate(customer, `/api/conversations/${pending.conversationId}/messages`, { content: "Contact alice@example.com", clientKey: crypto.randomUUID() });
    expect(blocked.status()).toBe(400);
    const cp = await customer.newPage(), tp = await tailor.newPage();
    await cp.goto(`/orders/${id}/chat`); await tp.goto(`/orders/${id}/chat`);
    const text = "A rounded collar, please.";
    await cp.getByLabel("Your message").fill(text);
    await cp.getByLabel(/Design attachment/).setInputFiles({ name: "collar.png", mimeType: "image/png", buffer: png });
    await expect(cp.getByAltText("Selected photo 1")).toBeVisible();
    await cp.getByRole("button", { name: "Submit for review" }).click();
    await expect(cp.getByRole("log")).toContainText(text);
    await expect(tp.getByRole("log")).not.toContainText(text);
    const own: MessageDTO[] = await (await customer.request.get(`/api/conversations/${pending.conversationId}/messages`)).json();
    const message = own.find(m => m.content === text)!;
    expect(message.moderationStatus).toBe("PENDING");
    expect((await outsider.request.get(`/api/conversations/${pending.conversationId}/messages`)).status()).toBe(403);
    expect((await outsider.request.get(message.imageUrl!)).status()).toBe(403);
    await approvePending(admin);
    await expect(tp.getByRole("log")).toContainText(text);
    await expect(tp.getByAltText("Reviewed design attachment")).toBeVisible();
    expect((await tailor.request.get(message.imageUrl!)).status()).toBe(200);
    await act(tailor, id, { kind: "timeline-confirm" });
    for (const action of ["schedule", "collect-pickup", "arrive-tailor"]) await act(admin, id, { kind: "logistics", action, ...courier });
    await tp.goto("/dashboard/tailor");
    const commission = tp.locator("article").filter({ has: tp.locator(`a[href="/orders/${id}"]`) });
    await commission.getByRole("button", { name: "Start stitching" }).click();
    await expect(commission.getByRole("button", { name: "Mark ready for delivery" })).toBeVisible();
    await commission.getByRole("button", { name: "Mark ready for delivery" }).click();
    await expect(commission.getByText("READY FOR DELIVERY", { exact: true })).toBeVisible();
    for (const action of ["dispatch-final", "deliver"]) await act(admin, id, { kind: "logistics", action, ...courier });
    const delivered = await readOrder(customer, id);
    expect(delivered.paid50Pickup && delivered.paid25Delivery).toBe(true); expect(delivered.paid25Approval).toBe(false);
    await act(customer, id, { kind: "alteration", alterationType: "DESIGN_PAID", notes: "Please add a decorative collar." });
    await approvePending(admin);
    let order = await readOrder(customer, id), alteration = order.alterations.find(a => !a.completed)!;
    await act(tailor, id, { kind: "alteration-quote", alterationId: alteration.id, amount: 49900 });
    order = await readOrder(customer, id); alteration = order.alterations.find(a => !a.completed)!;
    const locked = await mutate(admin, `/api/orders/${id}`, { kind: "logistics", action: "reverse-pickup", version: order.version, ...courier }, "PATCH");
    expect(locked.status()).toBe(409);
    await act(customer, id, { installment: "DESIGN", alterationId: alteration.id, quoteVersion: alteration.quoteVersion, quotedAmount: alteration.amount, acceptQuote: true, outcome: "success" }, true);
    for (const action of ["reverse-pickup", "reverse-arrive"]) await act(admin, id, { kind: "logistics", action, ...courier });
    for (const status of ["STITCHING", "READY_FOR_DELIVERY"]) await act(tailor, id, { kind: "production", status });
    for (const action of ["return-dispatch", "return-deliver"]) await act(admin, id, { kind: "logistics", action, ...courier });
    await act(customer, id, { kind: "alteration", alterationType: "FITTING_FREE", notes: "Please shorten the sleeves slightly." });
    await approvePending(admin);
    for (const action of ["reverse-pickup", "reverse-arrive"]) await act(admin, id, { kind: "logistics", action, ...courier });
    for (const status of ["STITCHING", "READY_FOR_DELIVERY"]) await act(tailor, id, { kind: "production", status });
    for (const action of ["return-dispatch", "return-deliver"]) await act(admin, id, { kind: "logistics", action, ...courier });
    await cp.goto(`/orders/${id}`);
    await cp.getByRole("button", { name: "Simulate approval payment failure" }).click();
    await expect(cp.getByRole("status")).toContainText("Demo payment failed");
    expect((await readOrder(customer, id)).status).toBe("DELIVERED_PENDING_APPROVAL");
    await cp.getByRole("button", { name: /Approve & Pay Final 25%/ }).click();
    await expect(cp.getByText("COMPLETED", { exact: true })).toBeVisible();
    await cp.getByLabel("Review (no names or contact information)").fill("Careful stitching and a comfortable fit.");
    await cp.getByRole("button", { name: "Submit rating & review for moderation" }).click();
    await approvePending(admin);
    const complete = await readOrder(customer, id);
    expect(complete.paid25Approval).toBe(true);
    expect(complete.alterations.filter(a => a.completed)).toHaveLength(2);
    expect(complete.payments.filter(p => p.status === "SUCCEEDED").reduce((n, p) => n + p.amount, 0)).toBe(complete.totalAmount + 49900);
    expect(complete.tailorNetPayout).toBe(complete.totalAmount - complete.commissionAmount + 49900);
    expect(complete.reviewStatus).toBe("APPROVED");
  } finally { await Promise.all([customer.close(), tailor.close(), admin.close(), outsider.close()]); }
});
