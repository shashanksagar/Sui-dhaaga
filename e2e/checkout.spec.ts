import { expect, test } from "@playwright/test";
import { address, mutate, png } from "./helpers";
import type { TailorCard } from "../src/lib/contracts";
test("signup and guided INR order with reference template, consent and private addresses", async ({ page, context }) => {
  const email = `browser-${crypto.randomUUID()}@test.local`;
  expect((await mutate(context, "/api/signup", { name: "Browser Customer", email, password: "A-test-password-2026", location: "Jaipur", phone: address.phone, role: "ADMIN" })).status()).toBe(400);
  await page.goto("/signup");
  await page.getByLabel("Your private name").fill("Browser Customer");
  await page.getByLabel("Indian city").selectOption("Jaipur");
  await page.getByLabel("Private phone number").fill(address.phone);
  await page.getByLabel("Email address").fill(email);
  await page.getByLabel("Password", { exact: true }).fill("A-test-password-2026");
  await page.getByRole("button", { name: "Create your account" }).click();
  await expect(page).toHaveURL(/\/orders$/);
  const tailors: TailorCard[] = await (await context.request.get("/api/tailors")).json();
  const tailor = tailors.find(t => t.id === "tailor-amara")!, garment = tailor.garmentCatalog[0];
  await page.goto("/order/new/tailor-amara");
  await page.getByLabel("Design specifications").fill("A rounded neckline and neat sleeve finishing.");
  await page.getByLabel(/Reference photos/).setInputFiles({ name: "inspiration.png", mimeType: "image/png", buffer: png });
  await expect(page.getByAltText("Selected photo 1")).toBeVisible();
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await page.getByLabel("Measurement method").selectOption("BOTH");
  for (const key of garment.requiredMeasurements) await page.getByLabel(`${key} (cm)`, { exact: true }).fill("90");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  for (const [label, value] of Object.entries({ "Private contact name": address.name, "Street / workshop address": address.line1, "PIN code": address.postalCode, "Private contact phone": address.phone })) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByLabel("City", { exact: true }).selectOption(address.city);
  await expect(page.getByLabel("Country", { exact: true })).toHaveValue("India");
  await page.getByRole("button", { name: "Continue", exact: true }).click();
  await expect(page.getByRole("button", { name: "Confirm order and agreed estimate" })).toBeDisabled();
  await page.getByRole("checkbox", { name: /Agree to Estimated Completion Duration/ }).check();
  await page.getByRole("button", { name: "Confirm order and agreed estimate" }).click();
  await expect(page).toHaveURL(/\/orders\/[^/]+$/);
  const id = page.url().split("/").at(-1)!;
  const order = await (await context.request.get(`/api/orders/${id}`)).json();
  expect(order.currency).toBe("INR"); expect(order.totalAmount).toBe(garment.finalDisplayPrice);
  expect(order.hasReferenceCloth).toBe(true); expect(order.measurementMode).toBe("BOTH");
  expect(order.paid50Pickup).toBe(false); expect(order.customerAgreedToTimeline).toBe(true);
  expect(order).not.toHaveProperty("pickupAddress"); expect(order).not.toHaveProperty("tailorIdentity");
  await page.reload();
  await expect(page.getByText("PENDING TIMELINE APPROVAL", { exact: true })).toBeVisible();
  const crossOrigin = await context.request.post(`/api/orders/${id}/payments`, { data: { version: order.version, installment: "APPROVAL", approved: true, outcome: "success" }, headers: { Origin: "https://not-sui.invalid" } });
  expect(crossOrigin.status()).toBe(403);
});
