import { expect, test } from "@playwright/test";
import { login, png } from "./helpers";
import type { MessageDTO, OrderDTO } from "../src/lib/contracts";
test("@restart retains approved order, three milestones, alteration history, masked chat and private bytes", async ({ context, page }) => {
  await login(context, "customer@sui.local");
  const orders: OrderDTO[] = await (await context.request.get("/api/orders")).json();
  const complete = orders.find(o => o.status === "COMPLETED" && o.alterations.length === 2)!;
  expect(complete).toBeDefined(); expect(complete.paid50Pickup && complete.paid25Delivery && complete.paid25Approval).toBe(true);
  expect(complete.payments.filter(p => p.status === "SUCCEEDED").reduce((n, p) => n + p.amount, 0)).toBe(complete.totalAmount + 49900);
  const messages: MessageDTO[] = await (await context.request.get(`/api/conversations/${complete.conversationId}/messages`)).json();
  const shared = messages.find(m => m.content === "A rounded collar, please.")!;
  expect(shared.moderationStatus).toBe("APPROVED");
  const image = await context.request.get(shared.imageUrl!);
  expect(image.status()).toBe(200); expect(await image.body()).toEqual(png);
  await page.goto(`/orders/${complete.id}`);
  await expect(page.getByText("COMPLETED", { exact: true })).toBeVisible();
  await page.goto(`/orders/${complete.id}/chat`);
  await expect(page.getByRole("log")).toContainText(shared.content);
  await expect(page.getByAltText("Reviewed design attachment")).toBeVisible();
});
